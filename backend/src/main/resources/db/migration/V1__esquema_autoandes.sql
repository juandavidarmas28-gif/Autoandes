CREATE TABLE cliente (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento VARCHAR2(11) NOT NULL UNIQUE,
    nombres VARCHAR2(120) NOT NULL,
    telefono VARCHAR2(15)
);

CREATE TABLE servicio (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(7) NOT NULL UNIQUE,
    nombre VARCHAR2(80) NOT NULL,
    precio NUMBER(10,2) NOT NULL CHECK (precio > 0),
    duracion_min NUMBER(4) NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1))
);

CREATE TABLE vehiculo (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR2(7) NOT NULL UNIQUE,
    marca VARCHAR2(40) NOT NULL,
    modelo VARCHAR2(40) NOT NULL,
    anio NUMBER(4) NOT NULL,
    cliente_id NUMBER NOT NULL,
    CONSTRAINT fk_vehiculo_cliente FOREIGN KEY (cliente_id) REFERENCES cliente(id)
);

CREATE TABLE orden_servicio (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR2(9) NOT NULL UNIQUE,
    fecha TIMESTAMP NOT NULL,
    vehiculo_id NUMBER NOT NULL,
    kilometraje NUMBER(7) NOT NULL,
    estado VARCHAR2(12) NOT NULL,
    total NUMBER(10,2) NOT NULL,
    usuario_registro VARCHAR2(30) NOT NULL,
    motivo_anulacion VARCHAR2(200),
    CONSTRAINT fk_orden_vehiculo FOREIGN KEY (vehiculo_id) REFERENCES vehiculo(id)
);

CREATE TABLE detalle_orden (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id NUMBER NOT NULL,
    servicio_id NUMBER NOT NULL,
    cantidad NUMBER(2) NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL,
    subtotal NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_detalle_orden FOREIGN KEY (orden_id) REFERENCES orden_servicio(id),
    CONSTRAINT fk_detalle_servicio FOREIGN KEY (servicio_id) REFERENCES servicio(id)
);

CREATE SEQUENCE seq_orden_numero START WITH 5 INCREMENT BY 1 NOCACHE;

CREATE TABLE usuarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(30) NOT NULL UNIQUE,
    password VARCHAR2(100) NOT NULL,
    nombrecompleto VARCHAR2(100) NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1))
);

CREATE TABLE roles (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(30) NOT NULL UNIQUE
);

CREATE TABLE usuario_roles (
    usuarioid NUMBER NOT NULL,
    rolid NUMBER NOT NULL,
    CONSTRAINT pk_usuario_roles PRIMARY KEY (usuarioid, rolid),
    CONSTRAINT fk_ur_usuario FOREIGN KEY (usuarioid) REFERENCES usuarios(id),
    CONSTRAINT fk_ur_rol FOREIGN KEY (rolid) REFERENCES roles(id)
);

CREATE INDEX ix_ur_rol ON usuario_roles(rolid);

CREATE INDEX ix_vehiculo_cliente ON vehiculo(cliente_id);
CREATE INDEX ix_orden_vehiculo_fecha ON orden_servicio(vehiculo_id, fecha);
CREATE INDEX ix_detalle_servicio ON detalle_orden(servicio_id);

